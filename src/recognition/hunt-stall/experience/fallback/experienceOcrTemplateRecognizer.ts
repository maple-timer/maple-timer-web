export function recognizeExperienceSymbol(bitmap: string[]): { text: string; confidence: number } {
  return EXPERIENCE_SYMBOL_TEMPLATES.reduce<{ text: string; confidence: number }>(
    (best, template) => {
      const confidence = compareExperienceInkBitmaps(bitmap, template.bitmap);
      return confidence > best.confidence ? { text: template.text, confidence } : best;
    },
    { text: "", confidence: 0 },
  );
}

export function recognizeExperienceDigitBitmap(bitmap: string[]): { text: string; confidence: number } {
  return recognizeExperienceDigit(bitmap);
}

export function recognizeExperienceDigit(bitmap: string[]): { text: string; confidence: number } {
  return EXPERIENCE_DIGIT_TEMPLATES.reduce<{ text: string; confidence: number }>(
    (best, template) => {
      const confidence = compareExperienceInkBitmaps(bitmap, template.bitmap);
      return confidence > best.confidence ? { text: template.text, confidence } : best;
    },
    { text: "", confidence: 0 },
  );
}

function compareExperienceInkBitmaps(a: string[], b: string[]): number {
  let intersection = 0;
  let union = 0;
  let backgroundMatches = 0;
  let backgroundTotal = 0;

  for (let y = 0; y < a.length; y += 1) {
    for (let x = 0; x < a[y].length; x += 1) {
      const aInk = a[y][x] === "1";
      const bInk = b[y][x] === "1";

      if (aInk || bInk) {
        union += 1;
        if (aInk && bInk) {
          intersection += 1;
        }
      } else {
        backgroundTotal += 1;
        backgroundMatches += 1;
      }
    }
  }

  const foregroundScore = union > 0 ? intersection / union : 0;
  const backgroundScore = backgroundTotal > 0 ? backgroundMatches / backgroundTotal : 1;
  return foregroundScore * 0.84 + backgroundScore * 0.16;
}
